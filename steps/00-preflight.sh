# --- shell rc hook (between markers, removed cleanly by uninstall) ----------
add_rc_block() {
  local rc="$1"
  if [ -f "$rc" ] && grep -qF "$RC_BEGIN" "$rc"; then ok "$rc already hooked"; return; fi
  [ -e "$rc" ] || record "path:$rc"
  if [ "$DRY_RUN" = "1" ]; then info "[dry-run] append env hook to $rc"; return; fi
  # ensure the file ends with a newline, then append the block (no blank line,
  # so install/uninstall cycles leave the file byte-identical)
  if [ -s "$rc" ] && [ -n "$(tail -c1 "$rc")" ]; then printf '\n' >> "$rc"; fi
  printf '%s\n[ -f "%s/env.sh" ] && . "%s/env.sh"\n%s\n' \
    "$RC_BEGIN" "$IBX_HOME" "$IBX_HOME" "$RC_END" >> "$rc"
  record "rcblock:$rc"
  ok "hooked $rc"
}
add_rc_block "$HOME/.zshrc"
add_rc_block "$HOME/.bash_profile"

load_env
